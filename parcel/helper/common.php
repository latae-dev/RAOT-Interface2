    function getStatus($status, $value = '', $depart = false) {

        if($status == 'draft') {
            return 'บันทึกร่าง';
        } else if($status == 'waiting' && $value != '' && !$depart) {
            $approve = getPositionApproveCode();

            return 'รออนุมัติ ' . $approve[$value];
        } else if($status == 'waiting' && $depart) {
            return 'รออนุมัติ ';
        } else if($status == 'approved') {
            return 'อนุมัติแล้ว';
        } else if($status == 'rejected') {
            return 'ไม่อนุมัติ';
        } else {
            return 'ไม่พบสถานะข้อมูล';
        }
    } 
