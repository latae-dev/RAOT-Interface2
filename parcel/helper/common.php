    function convertDateTime($datetime = "now", $timezone = "Asia/Bangkok") {
        try {
            $dt = new DateTime($datetime, new DateTimeZone($timezone));
            return $dt->format("Y-m-d H:i:s");
        } catch (Exception $e) {
            error_log("Date conversion error: " . $e->getMessage());
            return null;
        }
    }

    function setDateTimeFormat($datetime, $formatDate = "d-m-Y", $yearFormat = "TH", $timezone = "Asia/Bangkok") {
        try {
            $dt = new DateTime($datetime, new DateTimeZone($timezone));
            $formatted = $dt->format($formatDate);

            if (strtoupper($yearFormat) === "TH") {
                $year = (int)$dt->format("Y");
                $year_th = $year + 543;

                $formatted = preg_replace(
                    "/\b$year\b/u", 
                    $year_th, 
                    $formatted
                );
            }

            return $formatted;

        } catch (Exception $e) {
            error_log("Date conversion error: " . $e->getMessage());
            return null;
        }
    }

